import streamlit as st
from transformers import PreTrainedModel, PreTrainedTokenizerBase

from generation_pipeline import (
    build_structured_prompt,
    load_generation_model,
    run_generation_pipeline,
)
from structured_validator import NewsClassification


MODEL_NAME = "Qwen/Qwen2.5-1.5B-Instruct"


@st.cache_resource(max_entries=1)
def get_model() -> tuple[PreTrainedModel, PreTrainedTokenizerBase]:
    return load_generation_model(MODEL_NAME)


st.set_page_config(page_title="AG News classifier", page_icon=":material/article:")
st.title("AG News classifier")
st.write("Classify a news article as World, Sports, Business, or Sci/Tech.")

with st.form("classification_form"):
    article_text = st.text_area(
        "News article",
        placeholder="Paste or type a news article here...",
        height=180,
    )
    submitted = st.form_submit_button(
        "Classify article",
        type="primary",
        icon=":material/search:",
    )

if submitted:
    if not article_text.strip():
        st.error("Enter a news article before classifying it.")
    else:
        prompt = build_structured_prompt(article_text.strip())
        try:
            with st.spinner("Loading the model and classifying the article..."):
                model_bundle = get_model()
                result: NewsClassification = run_generation_pipeline(
                    prompt=prompt,
                    model_name=MODEL_NAME,
                    model_bundle=model_bundle,
                )

            st.subheader("Classification")
            st.metric("Category", result.category)
            st.metric("Model-estimated confidence", f"{result.confidence_score:.0%}")
            st.caption(
                "The confidence score is generated by the language model and may not "
                "be calibrated."
            )
            st.write("**Reasoning**")
            st.write(result.reasoning)

            with st.expander("View generated prompt"):
                st.code(prompt, language="text")
            with st.expander("View validated JSON"):
                st.json(result.model_dump())
        except Exception as exc:
            st.error("Classification failed. See the error details below.")
            st.exception(exc)
